// Writes the search-engine parts of the site from the word lists and HOLIDAYS, so they never
// drift from the game: each page's <head> tags (title, description, canonical, social preview,
// structured data), a word-list page per holiday at <holiday>/ideas/, the homepage's plain links,
// and sitemap.xml. In existing pages only the text between the <!-- …:start --> / <!-- …:end -->
// markers is touched; the game itself (shared/game.js and window.THEME) is only read.
//
// Run after changing words or holidays:   node tools/build_seo.js
// Also redraw the social preview images:  node tools/build_seo.js --images   (needs Edge or Chrome)
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const os = require("os");
const { execFileSync } = require("child_process");

const SITE = "https://bcbobin.github.io/charades/"; // change if the site moves to its own domain
const ROOT = path.resolve(__dirname, "..");
const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const write = (f, s) => fs.writeFileSync(path.join(ROOT, f), s);
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

// Same order and default labels as CATS in shared/game.js.
const CATS = { songs: "🎵 Song", movies: "🎬 Movie", actions: "🕺 Action", books: "📖 Book", quotes: "💬 Quote / Phrase", chars: "🦸 Character" };
// "🎬 Movie / TV" -> "Movies & TV"
const heading = label => label.split(" ").slice(1).join(" ").split(" / ").map(w => /[a-z]$/.test(w) ? w + "s" : w).join(" & ");

const HOW_TO = [
  "Split into two teams and share one phone.",
  "On your turn, pick one of three cards (a movie, song, book, action, phrase or character) or tap Random.",
  "Read it, hide the phone, tap Start and act it out without talking before the timer runs out.",
  "Tap Got it! if your team guesses it, then pass the phone to the other team. Most points wins."
];

// ---------- read the data the game already uses ----------
const homeHtml = read("index.html");
const HOLIDAYS = vm.runInNewContext(homeHtml.match(/const HOLIDAYS = (\[[\s\S]*?\n\]);/)[1], { nthWeekday() {}, easter() {} });
for (const h of HOLIDAYS) {
  const win = {};
  vm.runInNewContext(read(`${h.path}/index.html`).match(/<script>\s*(window\.THEME = [\s\S]*?)<\/script>/)[1], { window: win });
  h.theme = win.THEME;
  h.count = Object.values(h.theme.words).flatMap(c => [...(c.easy || []), ...(c.hard || [])]).length;
  h.url = SITE + h.path + "/";
  h.pageTitle = `${h.name} Charades – Free Online Game for Phones`;
  h.description = `Free ${h.name} charades game for your phone: two teams, a timer and ${h.count} ${h.name} ` +
    `charades ideas (movies, songs, characters and more). No app or sign-up.`;
}

// ---------- shared pieces ----------
function headTags({ title, description, url, image, jsonld }) {
  return `<!-- seo:start (generated by tools/build_seo.js) -->
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="canonical" href="${url}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Holiday Charades">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="${image}">
<meta property="og:image:width" content="1200">
<meta property="og:image:height" content="630">
<meta name="twitter:card" content="summary_large_image">
<script type="application/ld+json">
${JSON.stringify(jsonld, null, 2)}
</script>
<!-- seo:end -->`;
}
const app = (name, url, description) => ({
  "@type": "WebApplication", name, url, description,
  applicationCategory: "GameApplication", operatingSystem: "Any (web browser)", isAccessibleForFree: true,
  offers: { "@type": "Offer", price: "0", priceCurrency: "USD" }
});
const howToHtml = `<ol>${HOW_TO.map(s => `<li>${esc(s)}</li>`).join("")}</ol>`;

// Replaces the marked block, or on the first run, the given fallback (e.g. the old <title>).
function put(html, name, block, fallback, pad = "") {
  const re = new RegExp(`<!-- ${name}:start[\\s\\S]*?<!-- ${name}:end -->`);
  if (re.test(html)) return html.replace(re, () => block);
  if (!fallback.test(html)) throw new Error(`no place for ${name} block`);
  return html.replace(fallback, () => block + pad);
}

// ---------- holiday game pages: only the <head> tags ----------
for (const h of HOLIDAYS) {
  const head = headTags({
    title: h.pageTitle, description: h.description, url: h.url, image: h.url + "og.png",
    jsonld: { "@context": "https://schema.org", "@graph": [
      app(`${h.name} Charades`, h.url, h.description),
      { "@type": "BreadcrumbList", itemListElement: [
        { "@type": "ListItem", position: 1, name: "Holiday Charades", item: SITE },
        { "@type": "ListItem", position: 2, name: `${h.name} Charades`, item: h.url }] }
    ] }
  });
  let html = read(`${h.path}/index.html`);
  html = put(html, "seo", head, /<title>.*<\/title>/);
  write(`${h.path}/index.html`, html);
}

// ---------- word-list pages: <holiday>/ideas/ (wholly generated) ----------
for (const h of HOLIDAYS) {
  const T = h.theme;
  const game = read(`${h.path}/index.html`);
  // Reuse the game page's colors and fonts so the list looks like the holiday.
  const tokens = game.match(/<style>[\s\S]*?<\/style>/)[0];
  const fonts = game.match(/<link href="https:\/\/fonts\.googleapis\.com[^>]*>/)[0];
  const themeColor = game.match(/<meta name="theme-color"[^>]*>/)[0];
  const sections = Object.keys(CATS).map(id => {
    const w = T.words[id] || {};
    if (!(w.easy || []).length && !(w.hard || []).length) return "";
    const label = (T.labels || {})[id] || CATS[id];
    const list = (mode, name) => (w[mode] || []).length
      ? `<h3>${name}</h3>\n<ul class="words">${w[mode].map(x => `<li>${esc(x)}</li>`).join("")}</ul>\n` : "";
    return `<h2>${esc(label.split(" ")[0])} ${esc(h.name)} ${esc(heading(label))}</h2>\n${list("easy", "Easy")}${list("hard", "Hard")}`;
  }).join("");
  const others = HOLIDAYS.filter(o => o !== h).map(o => `<a href="../../${o.path}/ideas/">${o.emoji} ${esc(o.name)}</a>`).join("\n");
  const url = h.url + "ideas/";
  const title = `${h.count} ${h.name} Charades Ideas – Easy & Hard Word List`;
  const description = `${h.count} ${h.name} charades ideas for kids and adults: movies, songs, characters, actions and ` +
    `phrases, split into easy and hard. Free to print or play on your phone.`;
  const head = headTags({
    title, description, url, image: h.url + "og.png",
    jsonld: { "@context": "https://schema.org", "@type": "BreadcrumbList", itemListElement: [
      { "@type": "ListItem", position: 1, name: "Holiday Charades", item: SITE },
      { "@type": "ListItem", position: 2, name: `${h.name} Charades`, item: h.url },
      { "@type": "ListItem", position: 3, name: `${h.name} Charades Ideas`, item: url }] }
  });
  fs.mkdirSync(path.join(ROOT, h.path, "ideas"), { recursive: true });
  write(`${h.path}/ideas/index.html`, `<!doctype html>
<!-- Generated by tools/build_seo.js from ${h.path}/index.html. Edit the words there, then re-run it. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
${themeColor}
${head}
<link rel="icon" href="data:image/svg+xml,<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><text y='.9em' font-size='90'>${h.emoji}</text></svg>">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
${fonts}
<link rel="stylesheet" href="../../shared/ideas.css">
${tokens}
</head>
<body>
<main>
<nav class="crumbs"><a href="../../">🎭 Holiday Charades</a> › <a href="../">${esc(h.name)} Charades</a></nav>
<header>
  <div class="emoji">${h.emoji}</div>
  <h1>${h.count} ${esc(h.name)} Charades Ideas</h1>
  <p>Every word in <b>${esc(T.title)}</b>, our free ${esc(h.name)} charades game. Use the list for ${/^[AEIOU]/.test(h.name) ? "an" : "a"} ${esc(h.name)} party,
  in class or with family, or let the game deal the cards and keep time for you.</p>
  <a class="play" href="../">▶ Play ${esc(h.name)} Charades</a>
</header>
${sections}<h2>How to play charades</h2>
${howToHtml}
<div class="cta"><a class="play" href="../">▶ Play ${esc(h.name)} Charades</a></div>
<h2>More holiday charades ideas</h2>
<nav class="more">
${others}</nav>
</main>
</body>
</html>
`);
}

// ---------- homepage ----------
{
  const title = "Holiday Charades – Free Online Charades Game for Phones";
  const description = "Free charades game for phones: two teams, one phone, a timer and hundreds of word ideas for " +
    HOLIDAYS.map(h => h.name).join(", ").replace(/, ([^,]*)$/, " and $1") + ". No app or sign-up.";
  const head = headTags({
    title, description, url: SITE, image: SITE + "og.png",
    jsonld: { "@context": "https://schema.org", "@graph": [
      { "@type": "WebSite", name: "Holiday Charades", url: SITE },
      app("Holiday Charades", SITE, description),
      { "@type": "ItemList", itemListElement: HOLIDAYS.map((h, i) => ({ "@type": "ListItem", position: i + 1, name: `${h.name} Charades`, url: h.url })) }
    ] }
  });
  // Plain links for crawlers and no-JS visitors; the script below rebuilds them sorted by date.
  const links = `<!-- links:start (generated by tools/build_seo.js) -->
${HOLIDAYS.map(h => `  <a class="card" href="${h.path}/" style="--h-bg:${h.bg};--h-card:${h.card};--h-ink:${h.ink};--h-muted:${h.muted};--h-title:${h.title};--h-accent:${h.accent};--h-accent-ink:${h.accentInk};--h-font:&quot;${h.font}&quot;;--h-weight:${h.weight || 400}"><div><div class="emoji">${h.emoji}</div><div class="name">${esc(h.name)}</div></div><span class="go">›</span></a>`).join("\n")}
  <!-- links:end -->`;
  const about = `<!-- seo-about:start (generated by tools/build_seo.js) -->
  <section class="about">
    <h2>Free charades for every holiday</h2>
    <p>Holiday Charades is a free charades game that runs in your phone's browser. Each holiday has its own look and
    its own charades ideas, from easy ones for kids to hard ones for adults, mixed with everyday movies, songs and actions.</p>
    <h3>How to play</h3>
    ${howToHtml}
    <h3>Charades ideas by holiday</h3>
    <ul>${HOLIDAYS.map(h => `<li><a href="${h.path}/ideas/">${h.count} ${esc(h.name)} charades ideas</a></li>`).join("")}</ul>
  </section>
  <!-- seo-about:end -->`;
  let html = homeHtml;
  html = put(html, "seo", head, /<title>.*<\/title>\n<meta name="description"[^>]*>/);
  html = put(html, "links", links, /(?<=<nav class="grid" id="grid" aria-label="Holidays">)(?=<\/nav>)/, "\n  ");
  html = put(html, "seo-about", about, /(?=<footer>)/, "\n  ");
  write("index.html", html);
}

// ---------- sitemap ----------
const today = new Date().toISOString().slice(0, 10);
write("sitemap.xml", `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${[SITE, ...HOLIDAYS.flatMap(h => [h.url, h.url + "ideas/"])].map(u => `  <url><loc>${u}</loc><lastmod>${today}</lastmod></url>`).join("\n")}
</urlset>
`);

